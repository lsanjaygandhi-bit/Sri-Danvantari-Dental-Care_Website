// ------------------------------------------------------- inline → lite md --
function inlineMd($, el) {
  let s = '';
  $(el).contents().each((_, n) => {
    if (n.type === 'text') s += n.data.replace(/\s+/g, ' ');
    else if (n.name === 'br') s += '\n';
    else if (n.name === 'a') s += `[${norm($(n).text())}](${$(n).attr('href')})`;
    else if (n.type === 'tag') s += inlineMd($, n);
  });
  return s.split('\n').map(l => l.replace(/ +/g, ' ').trim()).join('\n').trim();
}
function leadText($, el) {
  const kids = $(el).children();
  if (!kids.length) return norm($(el).text());
  const first = $(el).contents().filter((_, n) => n.type === 'text' && n.data.trim()).first();
  return first.length ? norm(first[0].data) : '';
}

